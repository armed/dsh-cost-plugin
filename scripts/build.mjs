// Wrap src/client.js into the factory-form bundle DSH loads (lib/client.js). Prices live on the host (lib/index.js).
import { readFile, writeFile } from 'node:fs/promises'

const src = await readFile(new URL('../src/client.js', import.meta.url), 'utf8')
const body = src

const out = `/* dsh-cost-plugin client bundle - generated by scripts/build.mjs from src/client.js */
window.__ModuleLoader__.load({
  id: "dsh-cost-plugin",
  factory: (require) => {
    var module = { exports: {} };
    var exports = module.exports;
${body}
    return module.exports;
  }
});
`
await writeFile(new URL('../lib/client.js', import.meta.url), out)
console.log('built lib/client.js', out.length, 'bytes')
